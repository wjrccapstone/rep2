    private function computeTopProductGrouping(int $months, int $limit, bool $byCategory): array
    {
        $end = Carbon::now()->startOfMonth()->subMonth();
        $start = $end->copy()->subMonths($months - 1);

        $query = SaleItem::query()
            ->join('sales', 'sales.id', '=', 'sale_items.sale_id')
            ->whereNotNull('sales.sold_at')
            ->whereBetween('sales.sold_at', [$start->copy()->startOfMonth(), $end->copy()->endOfMonth()]);

        if ($byCategory) {
            $rows = $query->join('products', 'products.id', '=', 'sale_items.product_id')
                ->join('categories', 'categories.id', '=', 'products.category_id')
                ->selectRaw('categories.name as grouping_key, YEAR(sales.sold_at) as y, MONTH(sales.sold_at) as m, SUM(sale_items.quantity) as c')
                ->groupBy('categories.name', 'y', 'm')
                ->get();
        } else {
            $rows = $query->selectRaw('sale_items.product_name as grouping_key, YEAR(sales.sold_at) as y, MONTH(sales.sold_at) as m, SUM(sale_items.quantity) as c')
                ->groupBy('sale_items.product_name', 'y', 'm')
                ->get();
        }

        if ($rows->isEmpty()) {
            return [];
        }

        $half = (int) ceil($months / 2);

        return $rows->groupBy('grouping_key')
            ->map(function (Collection $group, string $grouping) use ($months, $half, $start) {
                $monthly = collect();
                $cursor = $start->copy();
                for ($i = 0; $i < $months; $i++) {
                    $y = (int) $cursor->format('Y');
                    $m = (int) $cursor->format('n');
                    $match = $group->first(fn ($r) => (int) $r->y === $y && (int) $r->m === $m);
                    $monthly->push((float) ($match->c ?? 0));
                    $cursor->addMonth();
                }

                $recentHalf = $monthly->slice(-$half)->sum();
                $priorHalf = $monthly->slice(0, $months - $half)->sum();
                $changePercent = $priorHalf > 0
                    ? round((($recentHalf - $priorHalf) / $priorHalf) * 100, 1)
                    : ($recentHalf > 0 ? 100.0 : 0.0);

                return [
                    'service' => $grouping,
                    'volume' => (int) $monthly->sum(),
                    'trend' => $monthly->values()->all(),
                    'changePercent' => $changePercent,
                ];
            })
            ->sortByDesc('volume')
            ->take($limit)
            ->values()
            ->all();
    }

    /**
