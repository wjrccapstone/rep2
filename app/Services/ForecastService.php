     * topProductCategories()/topProducts() (which rank by volume/units), this ranks by revenue —
     * services and product sales aren't on a comparable volume scale, but they are on a revenue
     * one, since both are money the business actually took in.
     */
    public function topEarners(int $months = 6, int $limit = 5): array
    {
        $key = "forecast:top-earners:{$months}:{$limit}:".Carbon::now()->format('Y-m');

        return Cache::remember($key, now()->addMinutes(self::MODEL_CACHE_TTL_MINUTES), fn () => $this->computeTopEarners($months, $limit));
    }

    private function computeTopEarners(int $months, int $limit): array
    {
        $end = Carbon::now()->startOfMonth()->subMonth();
        $start = $end->copy()->subMonths($months - 1);
        $half = (int) ceil($months / 2);

        $buildMonthly = function (Collection $group) use ($months, $half, $start): array {
            $monthly = collect();
            $cursor = $start->copy();
            for ($i = 0; $i < $months; $i++) {
                $y = (int) $cursor->format('Y');
                $m = (int) $cursor->format('n');
                $match = $group->first(fn ($r) => (int) $r->y === $y && (int) $r->m === $m);
                $monthly->push((float) ($match->c ?? 0));
                $cursor->addMonth();
            }

            $recentHalf = $monthly->slice(-$half)->sum();
            $priorHalf = $monthly->slice(0, $months - $half)->sum();
            $changePercent = $priorHalf > 0
                ? round((($recentHalf - $priorHalf) / $priorHalf) * 100, 1)
                : ($recentHalf > 0 ? 100.0 : 0.0);

            return [$monthly->values()->all(), (float) $monthly->sum(), $changePercent];
        };

        $serviceRows = JobOrder::query()
            ->join('services', 'services.id', '=', 'job_orders.service_id')
            ->whereNotNull('job_orders.planned_start_date')
            ->where('job_orders.payment_status', 'paid')
            ->whereBetween('job_orders.planned_start_date', [$start->copy()->startOfMonth(), $end->copy()->endOfMonth()])
            ->selectRaw('services.name as grouping_key, YEAR(job_orders.planned_start_date) as y, MONTH(job_orders.planned_start_date) as m, SUM(job_orders.cost) as c')
            ->groupBy('services.name', 'y', 'm')
            ->get();

        $productRows = SaleItem::query()
            ->join('sales', 'sales.id', '=', 'sale_items.sale_id')
            ->whereNotNull('sales.sold_at')
            ->whereBetween('sales.sold_at', [$start->copy()->startOfMonth(), $end->copy()->endOfMonth()])
            ->selectRaw('sale_items.product_name as grouping_key, YEAR(sales.sold_at) as y, MONTH(sales.sold_at) as m, SUM(sale_items.line_total) as c')
            ->groupBy('sale_items.product_name', 'y', 'm')
            ->get();

        $earners = collect();

        foreach ($serviceRows->groupBy('grouping_key') as $label => $group) {
            [$trend, $earned, $changePercent] = $buildMonthly($group);
            if ($earned > 0) {
                $earners->push([
                    'service' => $label,
                    'type' => 'service',
                    'typeLabel' => 'Service completed',
                    'volume' => round($earned, 2),
                    'trend' => $trend,
                    'changePercent' => $changePercent,
                ]);
            }
        }

        foreach ($productRows->groupBy('grouping_key') as $label => $group) {
            [$trend, $earned, $changePercent] = $buildMonthly($group);
            if ($earned > 0) {
                $earners->push([
                    'service' => $label,
                    'type' => 'product',
                    'typeLabel' => 'Product sale',
                    'volume' => round($earned, 2),
                    'trend' => $trend,
                    'changePercent' => $changePercent,
                ]);
            }
        }

        return $earners->sortByDesc('volume')->take($limit)->values()->all();
    }

    private function actualCount(Collection $dates): int
    {
        if ($dates->isEmpty()) {
            return 0;
        }

        return $this->periodQuery($dates)->count();
    }

    private function actualRevenue(Collection $dates): float
    {
        if ($dates->isEmpty()) {
            return 0.0;
        }

        return (float) $this->periodQuery($dates)->where('payment_status', 'paid')->sum('cost');
    }

    private function actualProductUnits(Collection $dates): int
    {
        if ($dates->isEmpty()) {
            return 0;
        }

        return (int) $this->productPeriodQuery($dates)->sum('sale_items.quantity');
    }

    private function actualProductRevenue(Collection $dates): float
    {
        if ($dates->isEmpty()) {
            return 0.0;
        }

        return (float) $this->productPeriodQuery($dates)->sum('sale_items.line_total');
    }

    /**
     * Single query matching SaleItem rows (via their sale's sold_at) whose (year, month) is in
     * the given set of dates, instead of running one query per date. Mirrors periodQuery() for
     * the product-sales side of the descriptive summary.
     */
    private function productPeriodQuery(Collection $dates)
    {
        $periods = $dates->map(fn (Carbon $d) => (int) $d->format('Ym'))->unique()->values()->all();
        $placeholders = implode(',', array_fill(0, count($periods), '?'));

        return SaleItem::query()
            ->join('sales', 'sales.id', '=', 'sale_items.sale_id')
            ->whereNotNull('sales.sold_at')
            ->whereRaw("(YEAR(sales.sold_at) * 100 + MONTH(sales.sold_at)) in ($placeholders)", $periods);
    }

    /**
     * Single query matching JobOrder rows whose (year, month) is in the given set of dates,
     * instead of running one query per date.
     */
    private function periodQuery(Collection $dates)
    {
        $periods = $dates->map(fn (Carbon $d) => (int) $d->format('Ym'))->unique()->values()->all();
        $placeholders = implode(',', array_fill(0, count($periods), '?'));

        return JobOrder::query()
            ->whereNotNull('planned_start_date')
            ->whereRaw("(YEAR(planned_start_date) * 100 + MONTH(planned_start_date)) in ($placeholders)", $periods);
    }

    private function compactNumber(float $value): string
    {
        $abs = abs($value);
        if ($abs >= 1_000_000) {
            return number_format($value / 1_000_000, 2).'M';
        }
        if ($abs >= 1_000) {
            return number_format($value / 1_000, 1).'K';
        }

        return number_format($value, 0);
    }

    /**
     * Fits (or reuses the cached fit of) the SARIMA model for a metric's full history.
     * Independent of forecastMonths/confidence, so the same fit serves every horizon
     * requested for this metric within the TTL.
     */
    private function fittedModel(string $metric, array $ys): Sarima
    {
        $key = 'forecast:model:'.$metric.':'.$this->seriesFingerprint($ys);

        return Cache::remember($key, now()->addMinutes(self::MODEL_CACHE_TTL_MINUTES), function () use ($ys) {
            $model = Sarima::search($ys, self::SEASONAL_PERIOD);
            if ($model === null || ! $model->fitted) {
                // Last-resort fallback for series too short/degenerate for any order search to fit: naive drift ARIMA(0,1,0).
                $model = new Sarima($ys, 0, 1, 0, 0, 0, 0, self::SEASONAL_PERIOD);
                $model->fit();
            }

            return $model;
        });
    }

    private function cachedAccuracy(string $metric, array $ys, int $seasonalPeriod, Sarima $fullModel): array
    {
        $key = 'forecast:accuracy:'.$metric.':'.$this->seriesFingerprint($ys);

        return Cache::remember($key, now()->addMinutes(self::MODEL_CACHE_TTL_MINUTES), fn () => $this->accuracy($ys, $seasonalPeriod, $fullModel));
    }

    private function seriesFingerprint(array $ys): string
    {
        return hash('crc32', implode(',', $ys));
    }

    /**
     * Hold-out backtest: refit on all but the most recent months (using the same order
     * already selected against the full series, rather than re-running the grid search),
     * forecast that held-out window, and score the forecast against what actually happened
     * using MAE, RMSE, and MAPE (MAPE skips any zero-actual month to avoid division by zero).
     */
    private function accuracy(array $ys, int $seasonalPeriod, Sarima $fullModel): array
    {
        $none = ['available' => false, 'mae' => null, 'mse' => null, 'rmse' => null, 'mape' => null, 'holdoutMonths' => 0];

        $n = count($ys);
        $holdout = min(12, max(3, (int) floor($n * 0.2)));
        $trainSize = $n - $holdout;

        if ($trainSize < 4) {
            return $none;
        }

        $train = array_slice($ys, 0, $trainSize);
        $actual = array_slice($ys, $trainSize);

        $model = new Sarima($train, $fullModel->p, $fullModel->d, $fullModel->q, $fullModel->P, $fullModel->D, $fullModel->Q, $seasonalPeriod);
        if (! $model->fit()) {
            $model = new Sarima($train, 0, 1, 0, 0, 0, 0, $seasonalPeriod);
            $model->fit();
        }

        if (! $model->fitted) {
            return $none;
        }

        $predicted = collect($model->forecast($holdout, 1.0))
            ->pluck('value')
            ->map(fn ($v) => max(0, $v))
            ->all();

        $absErrors = [];
        $sqErrors = [];
        $pctErrors = [];
        foreach ($actual as $i => $a) {
            if (! array_key_exists($i, $predicted)) {
                continue;
            }
            $p = $predicted[$i];
            $absErrors[] = abs($a - $p);
            $sqErrors[] = ($a - $p) ** 2;
            if ($a != 0.0) {
                $pctErrors[] = abs(($a - $p) / $a);
            }
        }

        if ($absErrors === []) {
            return $none;
        }

        return [
            'available' => true,
            'mae' => round(array_sum($absErrors) / count($absErrors), 2),
            'mse' => round(array_sum($sqErrors) / count($sqErrors), 2),
            'rmse' => round(sqrt(array_sum($sqErrors) / count($sqErrors)), 2),
            'mape' => $pctErrors !== [] ? round((array_sum($pctErrors) / count($pctErrors)) * 100, 1) : null,
            'holdoutMonths' => $holdout,
        ];
    }

    protected function monthlySeries(string $metric): Collection
    {
        if ($metric === 'product_sales') {
            $query = SaleItem::query()
                ->join('sales', 'sales.id', '=', 'sale_items.sale_id')
                ->whereNotNull('sales.sold_at')
                ->selectRaw('YEAR(sales.sold_at) as y, MONTH(sales.sold_at) as m, SUM(sale_items.quantity) as c');
        } elseif ($metric === 'product_revenue') {
            $query = SaleItem::query()
                ->join('sales', 'sales.id', '=', 'sale_items.sale_id')
                ->whereNotNull('sales.sold_at')
                ->selectRaw('YEAR(sales.sold_at) as y, MONTH(sales.sold_at) as m, SUM(sale_items.line_total) as c');
        } else {
            $query = JobOrder::query()->whereNotNull('planned_start_date');

            if ($metric === 'revenue') {
                $query->where('payment_status', 'paid')
                    ->selectRaw('YEAR(planned_start_date) as y, MONTH(planned_start_date) as m, SUM(cost) as c');
            } else {
                $query->selectRaw('YEAR(planned_start_date) as y, MONTH(planned_start_date) as m, COUNT(*) as c');
            }
        }

        $rows = $query->groupBy('y', 'm')
            ->orderBy('y')->orderBy('m')
            ->get()
            ->keyBy(fn ($r) => sprintf('%04d-%02d', $r->y, $r->m));

        if ($rows->isEmpty()) {
            return collect();
        }

        $first = Carbon::createFromDate((int) $rows->first()->y, (int) $rows->first()->m, 1)->startOfDay();
        $last = Carbon::createFromDate((int) $rows->last()->y, (int) $rows->last()->m, 1)->startOfDay();

        // The current calendar month is still in progress and its totals are necessarily
        // incomplete, so it's excluded to avoid distorting the fit, trend, and backtest.
        $currentMonthStart = Carbon::now()->startOfMonth();
        if ($last->greaterThanOrEqualTo($currentMonthStart)) {
            $last = $currentMonthStart->copy()->subMonth();
        }

        if ($last->lessThan($first)) {
            return collect();
        }

        $series = collect();
        $cursor = $first->copy();
        while ($cursor->lessThanOrEqualTo($last)) {
            $key = $cursor->format('Y-m');
            $series->push([
                'date' => $cursor->copy(),
                'month' => (int) $cursor->format('n'),
                'value' => (float) ($rows[$key]->c ?? 0),
            ]);
            $cursor->addMonth();
        }

        return $series;
    }

    private function linearRegression(array $xs, array $ys): array
    {
        $n = count($xs);
        $sumX = array_sum($xs);
        $sumY = array_sum($ys);
        $sumXY = 0;
        $sumXX = 0;
        foreach ($xs as $i => $x) {
            $sumXY += $x * $ys[$i];
            $sumXX += $x * $x;
        }

        $denominator = ($n * $sumXX - $sumX ** 2) ?: 1;
        $slope = ($n * $sumXY - $sumX * $sumY) / $denominator;
        $intercept = ($sumY - $slope * $sumX) / $n;

        return [$intercept, $slope];
    }

    private function stdDev(array $values): float
    {
        $n = count($values);
        if ($n < 2) {
            return 0.0;
        }
        $mean = array_sum($values) / $n;
        $variance = array_sum(array_map(fn ($v) => ($v - $mean) ** 2, $values)) / ($n - 1);

        return sqrt($variance);
    }

    private function median(array $values): float
    {
        sort($values);
        $n = count($values);
        if ($n === 0) {
            return 0.0;
        }
        $mid = (int) floor(($n - 1) / 2);
        if ($n % 2 === 0) {
            return ($values[$mid] + $values[$mid + 1]) / 2;
        }

        return (float) $values[$mid];
    }

